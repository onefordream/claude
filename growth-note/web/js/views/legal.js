function tokushoho(op, pricing) {
  const row = (k, v) => html`<tr><th>${k}</th><td>${v}</td></tr>`;
  return html`<div class="legal-table-wrap"><table class="legal-table">
    ${row('販売事業者', op.name || UNSET('運営者名'))}
    ${row('運営統括責任者', op.representative || UNSET('責任者名'))}
    ${row('所在地', op.address || '請求があった場合、遅滞なく開示します')}
    ${row('電話番号', op.phone || '請求があった場合、遅滞なく開示します')}
    ${row('メールアドレス', op.email || UNSET('お問い合わせメールアドレス'))}
    ${row('販売価格', html`プロプラン：月額${yen(pricing.month.amount)}／年額${yen(pricing.year.amount)}（いずれも税込）<br>フリープランは無料です`)}
    ${row('商品代金以外の必要料金', 'インターネット接続にかかる通信料はお客様のご負担となります')}
    ${row('お支払い方法', 'クレジットカード（Stripe による決済）')}
    ${row('お支払い時期', html`お申し込み時に決済します。初回のみ${pricing.trialDays}日間の無料体験期間があり、終了時に初回の料金を請求します。以後は、更新日ごとに自動で請求します`)}
    ${row('サービスの提供時期', '決済の完了後（無料体験の場合はお申し込み後）、すぐにご利用いただけます')}
    ${row('解約・キャンセル', 'アプリ内の「プランとお支払い」からいつでも解約できます。解約後も、支払い済みの期間の終了までご利用いただけ、次回以降の請求は発生しません')}
    ${row('返品・返金', 'デジタルサービスの性質上、支払い済みの料金の返金はいたしかねます（法令に定める場合を除きます）')}
    ${row('動作環境', '最新版の Safari・Chrome・Edge・Firefox（スマートフォン・パソコン）')}
  </table></div>`;
}

const TITLES = { terms: '利用規約', privacy: 'プライバシーポリシー', tokushoho: '特定商取引法に基づく表記' };

export async function render(root, { page }, { state }) {
  const { operator, pricing, termsVersion } = await api('/public/config');
  const body = page === 'terms' ? terms(operator, pricing) : page === 'privacy' ? privacy(operator) : tokushoho(operator, pricing);
  mount(root, html`
    <header class="page-head with-back">
      <a class="icon-btn" href="${state.me ? '#/me' : '#/welcome'}" aria-label="戻る">${icon('caretLeft', { size: 20 })}</a>
      <div class="page-head-main"><h1 class="page-title page-title-sm">${TITLES[page]}</h1></div>
    </header>
    <article class="legal">${body}
      ${page !== 'tokushoho' ? html`<p class="hint">制定日：${termsVersion.replace(/-/g, '/')}</p>` : ''}
    </article>
    <nav class="footer-links">${Object.entries(TITLES).filter(([k]) => k !== page).map(([k, t]) => html`<a href="#/legal/${k}">${t}</a>`)}</nav>`);
}
